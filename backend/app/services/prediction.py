# Weight of the win/loss classifier when tilting the simulated run means. The runs model keeps
# the majority say; the classifier corrects cases where records and matchup edges disagree with
# raw scoring rates (e.g. a high-scoring, high-conceding team with a losing record).
CLASSIFIER_BLEND_WEIGHT = .35
# Total-runs variance inflation of the correlated gamma-Poisson process, used to convert
# win-probability tilts into run-margin tilts via a normal approximation.
MARGIN_VARIANCE_INFLATION = 1.6


def apply_market_consensus_anchor(home_runs: float, away_runs: float,
                                  market: dict[str, Any] | None,
                                  league: str) -> tuple[float, float, dict[str, Any]]:
    """Conservatively anchor model means to a real pregame multi-book consensus.

    A total or moneyline is valuable external information, but it is neither an observed result
    nor permission to copy the book. The model retains the majority weight, while the consensus
    corrects implausible total and win-probability divergence. A bare number without provider,
    collection time, or bookmaker count is never treated as real market evidence.
    """
    market = market or {}
    provenance = bool(market.get("provider") or market.get("collected_at") or
                      int(market.get("bookmaker_count") or 0) > 0)
    before_total = home_runs + away_runs
    before_margin = home_runs - away_runs
    disabled = {
        "enabled": False,
        "method": "PREGAME_MULTI_BOOK_CONSENSUS_SHRINKAGE_V1",
        "reason": "NO_VERIFIED_PREGAME_MARKET",
        "model_home_before": round(home_runs, 6),
        "model_away_before": round(away_runs, 6),
        "model_total_before": round(before_total, 6),
    }
    if not provenance:
        return home_runs, away_runs, disabled

    def number(key: str) -> float | None:
        value = market.get(key)
        if value is None:
            return None
        try:
            parsed = float(value)
        except (TypeError, ValueError):
            return None
        return parsed if math.isfinite(parsed) else None

    total_line = number("total_line")
    total_line = total_line if total_line is not None and 4 <= total_line <= 20 else None
    home_probability, away_probability = number("home_implied_probability"), number("away_implied_probability")
    if (home_probability is not None and away_probability is not None and
            home_probability > 0 and away_probability > 0):
        probability_sum = home_probability + away_probability
        market_home_probability = home_probability / probability_sum
    else:
        market_home_probability = None
    home_spread = number("home_spread")
    books = max(1, int(market.get("bookmaker_count") or 1))
    total_weight = min(.40, .20 + .025 * min(books, 8)) if total_line is not None else 0.0
    probability_weight = min(.35, .16 + .0225 * min(books, 8)) if market_home_probability is not None else 0.0

    anchored_total = before_total
    if total_line is not None:
        # Keep a single stale or erroneous feed from shifting a projection by several runs.
        target_total = max(before_total - 3.0, min(before_total + 3.0, total_line))
        anchored_total = (1 - total_weight) * before_total + total_weight * target_total

    margin_sd = max(1.0, (MARGIN_VARIANCE_INFLATION * anchored_total) ** .5)
    model_home_probability = NormalDist().cdf(before_margin / margin_sd)
    market_probability_source = "H2H_NO_VIG"
    if market_home_probability is None and home_spread is not None and home_spread != 0:
        # A run line reliably identifies the favourite, but without its price it does not imply
        # a 50% cover rate. Use direction only and at a much weaker weight.
        market_home_probability = .54 if home_spread < 0 else .46
        probability_weight = .10
        market_probability_source = "SPREAD_DIRECTION_ONLY"
    anchored_probability = model_home_probability
    anchored_margin = before_margin
    if market_home_probability is not None:
        anchored_probability = ((1 - probability_weight) * model_home_probability
                                + probability_weight * max(.05, min(.95, market_home_probability)))
        target_margin = NormalDist().inv_cdf(max(.03, min(.97, anchored_probability))) * margin_sd
        anchored_margin = max(before_margin - 2.0, min(before_margin + 2.0, target_margin))

    anchored_total = max(1.2, min(20.0, anchored_total))
    anchored_margin = max(-(anchored_total - 1.2), min(anchored_total - 1.2, anchored_margin))
    anchored_home = max(.6, min(10.0, (anchored_total + anchored_margin) / 2))
    anchored_away = max(.6, min(10.0, (anchored_total - anchored_margin) / 2))
    return anchored_home, anchored_away, {
        "enabled": bool(total_weight or probability_weight),
        "method": "PREGAME_MULTI_BOOK_CONSENSUS_SHRINKAGE_V1",
        "provider": market.get("provider"),
        "collected_at": market.get("collected_at"),
        "bookmaker_count": books,
        "total_line": total_line,
        "home_spread": home_spread,
        "market_home_probability": (round(market_home_probability, 6)
                                    if market_home_probability is not None else None),
        "market_probability_source": market_probability_source if market_home_probability is not None else None,
        "total_weight": round(total_weight, 6),
        "probability_weight": round(probability_weight, 6),
        "model_home_before": round(home_runs, 6),
        "model_away_before": round(away_runs, 6),
        "model_total_before": round(before_total, 6),
        "model_home_probability_before": round(model_home_probability, 6),
        "anchored_home_probability": round(anchored_probability, 6),
        "anchored_home": round(anchored_home, 6),
        "anchored_away": round(anchored_away, 6),
        "anchored_total": round(anchored_home + anchored_away, 6),
    }


# How much extra run-scoring spread each upset factor may add, in gamma-variance units. Small
# on purpose: the base spread is fitted against real games, and these push a specific matchup
# off that baseline rather than replacing it. The cap keeps any single game from turning into
# noise no matter how many factors line up at once.
MAX_VOLATILITY_BONUS = .06
UPSET_VOLATILITY_WEIGHTS = {
    # A slugging matchup against shaky pitching does not just score more, it scores less
    # predictably: innings end in crooked numbers rather than a steady drip.
    "matchup_scoring": .030,
    # Wind and temperature that move run expectancy also fatten the tails, which the run-mean
    # multiplier alone cannot express.
    "weather": .020,
    # A club whose leverage arms are used up cannot protect a lead, so its game states diverge.
    "bullpen_fatigue": .030,
    # Travel and compressed scheduling show up as ragged execution, not as a uniform decline.
    "schedule_fatigue": .020,
    # An unannounced starter is a genuinely unknown quantity, not an average one.
    "starter_unconfirmed": .015,
}


def _volatility_factors(features: dict[str, Any], pregame: dict[str, Any],
                        combined_ops: float, combined_whip: float) -> dict[str, Any]:
    """Widen the run distribution for the conditions that actually produce upsets.

    Favourites lose when a game stops behaving like its averages: a bullpen that cannot hold a
    lead, a wind that turns fly balls into home runs, a club on its fourth city in five days, a
    starter nobody has announced. None of that makes the weaker club better on average, which is
    why feeding it into the run means barely moves a forecast. It makes the result less certain,
    and an uncertain result is exactly what gives the underdog its chance.
    """
    def clamp(value: float) -> float:
        return max(0.0, min(1.0, value))

    # Both clubs share the conditions of the ballpark they are standing in.
    matchup = clamp((combined_ops - 1.44) / .16) * .6 + clamp((combined_whip - 2.70) / .40) * .4
    weather_multiplier = float(features.get("weather_run_multiplier") or 1.0)
    weather = clamp(abs(weather_multiplier - 1.0) / .08) if features.get("weather_available") else 0.0
    shared = (UPSET_VOLATILITY_WEIGHTS["matchup_scoring"] * matchup
              + UPSET_VOLATILITY_WEIGHTS["weather"] * weather)

    bullpen = pregame.get("bullpen") or {}
    schedule = pregame.get("schedule") or {}
    sides: dict[str, float] = {}
    detail: dict[str, Any] = {}
    for side in ("home", "away"):
        workload = bullpen.get(side) or {}
        relief = clamp(float(workload.get("fatigue_index") or 0.0)) if workload.get("available") else 0.0
        travel = clamp(float((schedule.get(side) or {}).get("fatigue_index") or 0.0) / .25)
        unconfirmed = 0.0 if features.get(f"{side}_starter_confirmed") else 1.0
        bonus = (UPSET_VOLATILITY_WEIGHTS["bullpen_fatigue"] * relief
                 + UPSET_VOLATILITY_WEIGHTS["schedule_fatigue"] * travel
                 + UPSET_VOLATILITY_WEIGHTS["starter_unconfirmed"] * unconfirmed)
        sides[side] = min(MAX_VOLATILITY_BONUS, bonus)
        detail[side] = {
            "bullpen_fatigue": round(relief, 4), "schedule_fatigue": round(travel, 4),
            "starter_unconfirmed": bool(unconfirmed),
            "bullpen_available": bool(workload.get("available")),
            "volatility_bonus": round(sides[side], 5),
        }
    return {
        "shared_volatility": min(MAX_VOLATILITY_BONUS, shared),
        "home_volatility": sides["home"],
        "away_volatility": sides["away"],
        "detail": {
            "matchup_scoring": round(matchup, 4),
            "weather": round(weather, 4),
            "weather_run_multiplier": round(weather_multiplier, 4),
            "shared_bonus": round(min(MAX_VOLATILITY_BONUS, shared), 5),
            **detail,
        },
        "weights": UPSET_VOLATILITY_WEIGHTS,
        "maximum_bonus": MAX_VOLATILITY_BONUS,
    }


# An upset call has to clear the posted price by a real margin before it is worth naming. Below
# this the gap is inside the noise of a two-parameter calibration map fitted on a few hundred
# games, and every game on the slate would carry one.
UPSET_EDGE_THRESHOLD = .04
# A volatility factor is only worth naming to a reader once it is actually elevated.
VOLATILITY_REPORTING_FLOOR = .25


def upset_watch(home_probability: float, market: dict[str, Any], volatility: dict[str, Any],
                home_name: str, away_name: str) -> dict[str, Any]:
    """Whether the club the market has as the underdog is worth a second look, and why.

    Two separate things have to be true before an upset is worth naming. The result has to be
    genuinely uncertain - which is what the volatility factors above widen - and the price has
    to be paying more for that uncertainty than we think it is worth. A wide game at a fair
    price is not an opportunity, and a mispriced game nobody can call is not either.

    This is deliberately not sold as a validated edge. The model has not yet shown it beats the
    closing moneyline out of sample; derived_market_calibration accumulates exactly that
    evidence, and until it says otherwise this block is an observation with its reasons attached.
    """
    market_home = market.get("home_implied_probability")
    market_away = market.get("away_implied_probability")
    priced = (isinstance(market_home, (int, float)) and isinstance(market_away, (int, float))
              and 0 < float(market_home) < 1 and 0 < float(market_away) < 1)
    # The market decides who the underdog is; that is the whole point of comparing against it.
    # With no price, fall back to our own weaker club so the card can still explain the shape.
    if priced:
        underdog = "HOME" if float(market_home) < float(market_away) else "AWAY"
    else:
        underdog = "HOME" if home_probability < .5 else "AWAY"
    model_probability = home_probability if underdog == "HOME" else 1 - home_probability
    market_probability = None
    if priced:
        total = float(market_home) + float(market_away)
        # The two sides are already de-vigged upstream, but renormalise so the pair sums to one
        # whatever the provider sent.
        market_probability = (float(market_home) if underdog == "HOME" else float(market_away)) / total
    edge = model_probability - market_probability if market_probability is not None else None
    detail = volatility.get("detail") or {}
    side = detail.get("home" if underdog == "HOME" else "away") or {}
    opponent = detail.get("away" if underdog == "HOME" else "home") or {}
    underdog_name = home_name if underdog == "HOME" else away_name
    favorite_name = away_name if underdog == "HOME" else home_name
    reasons: list[str] = []
    if float(opponent.get("bullpen_fatigue") or 0) >= VOLATILITY_REPORTING_FLOOR:
        reasons.append(f"{favorite_name} 불펜 소모 큼 · 리드를 지키기 어려움")
    if float(opponent.get("schedule_fatigue") or 0) >= VOLATILITY_REPORTING_FLOOR:
        reasons.append(f"{favorite_name} 이동·일정 피로 누적")
    if opponent.get("starter_unconfirmed"):
        reasons.append(f"{favorite_name} 선발 미확정 · 실제 등판 편차가 큼")
    if float(detail.get("weather") or 0) >= VOLATILITY_REPORTING_FLOOR:
        reasons.append("날씨가 득점 환경을 평소와 다르게 만듦")
    if float(detail.get("matchup_scoring") or 0) >= VOLATILITY_REPORTING_FLOOR:
        reasons.append("타선 대비 투수력이 약한 난타전 구도")
    if float(side.get("bullpen_fatigue") or 0) >= VOLATILITY_REPORTING_FLOOR:
        reasons.append(f"{underdog_name}도 불펜 소모가 커 양방향 변동성")
    return {
        "underdog": underdog,
        "underdog_source": "MARKET" if priced else "MODEL",
        "model_probability": round(model_probability, 4),
        "market_probability": round(market_probability, 4) if market_probability is not None else None,
        "edge": round(edge, 4) if edge is not None else None,
        "edge_threshold": UPSET_EDGE_THRESHOLD,
        # Named only when the price is beaten by more than the threshold. Never on model
        # confidence alone: without a price there is nothing to disagree with.
        "flagged": bool(edge is not None and edge >= UPSET_EDGE_THRESHOLD),
        "comparable": bool(edge is not None),
        "volatility_bonus": round(float(volatility.get("shared_volatility") or 0)
                                  + float(side.get("volatility_bonus") or 0), 5),
        "reasons": reasons,
        "validation": "NOT_YET_PROVEN_AGAINST_CLOSING_PRICE",
    }


def blend_classifier_into_means(logistic: float, home_runs: float, away_runs: float) -> tuple[float, float]:
    """Shift the run means so the simulated win probability blends runs and classifier signals."""
    normal = NormalDist()
    margin = home_runs - away_runs
    margin_sd = max(1.0, (MARGIN_VARIANCE_INFLATION * (home_runs + away_runs)) ** .5)
    runs_implied = normal.cdf(margin / margin_sd)
    target = min(.97, max(.03,
        (1 - CLASSIFIER_BLEND_WEIGHT) * runs_implied + CLASSIFIER_BLEND_WEIGHT * min(.97, max(.03, logistic))))
    shift = normal.inv_cdf(target) * margin_sd - margin
    # Split the tilt across both clubs so the expected total is preserved.
    return max(.6, home_runs + shift / 2), max(.6, away_runs - shift / 2)


def _apply_daily_bullpen_workload(staff: dict[str, Any], workload: dict[str, Any] | None) -> dict[str, Any]:
    """Degrade the relief plan only when official prior-game usage is available."""
    output = {**staff, "bullpen": dict(staff["bullpen"])}
    if not workload or not workload.get("available"):
        output["daily_workload"] = {"available": False}
        return output
    fatigue = max(0.0, min(1.0, float(workload.get("fatigue_index") or 0.0)))
    tier_fatigue = workload.get("tier_fatigue") or {}
    for tier in output["bullpen"]:
        tier_value = max(0.0, min(1.0, float(tier_fatigue.get(tier, fatigue))))
        penalty = (.16 if tier == "high_leverage" else (.11 if tier == "middle" else .07)) if tier_fatigue else .10
        output["bullpen"][tier] = round(min(1.8, float(output["bullpen"][tier]) * (1 + penalty * tier_value)), 4)
    output["daily_workload"] = {
        "available": True, "source": workload.get("source"), "fatigue_index": fatigue,
        "pitches": workload.get("pitches") or {},
        "high_load_arms": workload.get("high_load_arms") or [],
        "confirmed_unavailable_arms": workload.get("confirmed_unavailable_arms") or [],
        "workload_unavailable_arms": workload.get("workload_unavailable_arms") or [],
        "tier_fatigue": tier_fatigue, "arms": workload.get("arms") or [],
    }
    return output


def build_score_estimates(top_scores: list[dict[str, Any]], primary_score: dict[str, Any],
                          home_expected: float, away_expected: float) -> dict[str, Any]:
    """Complementary point estimates of the same complete simulation distribution.

    - mean: distribution mean (the gamma shocks preserve expected means), minimizes per-team
      squared error and differs game to game — used as the displayed headline score.
    - mode: the single most frequent exact score with its honest (low) probability.
    - representative: the complete-population Bayes-median scenario, constrained by
      the same run-line and headline-total directions shown beside it.
    """
    mode_score = top_scores[0] if top_scores else primary_score
    estimates: dict[str, Any] = {
        "headline": "MEAN",
        "mean": {"away": round(away_expected, 1), "home": round(home_expected, 1)},
        "mode": {"away": mode_score["away"], "home": mode_score["home"],
                 "count": mode_score.get("count"), "probability": mode_score.get("probability")},
        "full_distribution": {
            "away": mode_score["away"], "home": mode_score["home"],
            "count": mode_score.get("count"), "probability": mode_score.get("probability"),
        },
        "representative": {
            "away": primary_score["away"], "home": primary_score["home"],
            "count": primary_score.get("count"), "probability": primary_score.get("probability"),
            "selection_method": primary_score.get("selection_method"),
            "selection_score": primary_score.get("selection_score"),
            "population_coverage": primary_score.get("population_coverage"),
            "projects_favorite_cover": primary_score.get("projects_favorite_cover"),
            "run_line_conditioning": primary_score.get("run_line_conditioning"),
            "favorite_cover_probability_given_win": primary_score.get("favorite_cover_probability_given_win"),
            "favorite_run_line": primary_score.get("favorite_run_line"),
            "minimum_favorite_margin": primary_score.get("minimum_favorite_margin"),
            "run_line_source": primary_score.get("run_line_source"),
            "headline_total_line": primary_score.get("headline_total_line"),
            "headline_total_pick": primary_score.get("headline_total_pick"),
            "scenario_probability": primary_score.get("scenario_probability"),
            "scenario_conditioning": primary_score.get("scenario_conditioning"),
        },
    }
    estimates["winner_conditional"] = dict(estimates["representative"])
    return estimates


def _confidence(features: dict[str, Any], disagreement: float) -> tuple[int, str, list[str]]:
    score = 58
    missing = []
    if features["home_starter_confirmed"] and features["away_starter_confirmed"]:
        score += 16
    else:
        missing.append("선발투수 미확정 또는 기록 부족")
    if features["home_lineup_confirmed"] and features["away_lineup_confirmed"]:
        score += 8
        if min(int(features["home_lineup_bvp_coverage"]), int(features["away_lineup_bvp_coverage"])) >= 3:
            score += 3
    else:
        missing.append("실제 라인업 미확정")
    if features.get("bullpen_workload_available"):
        score += 3
    else:
        missing.append("공식 일일 불펜 소모 데이터 미확보")
    if features.get("weather_available"):
        score += 1
    elif features.get("static_park_factor") != 1.0:
        missing.append("경기 시각 날씨 미공개(정적 구장 계수만 반영)")
    if min(int(features.get("home_lineup_platoon_coverage", 0)),
           int(features.get("away_lineup_platoon_coverage", 0))) < 5:
        missing.append("좌우 투수 상대 타선 표본 부족")
    if not features.get("fielding_data_available"):
        missing.append("공식 팀 수비 세부 지표 미확보")
    if not features.get("baserunning_data_available"):
        missing.append("공식 주루 지표 미확보")
    if not features.get("catcher_data_available"):
        missing.append("공식 포수 제어 지표 미확보")
    recent_games = min(int(features["recent_home_games"]), int(features["recent_away_games"]))
    score += min(10, recent_games)
    if recent_games < 10:
        missing.append("최근 10경기 표본 부족")
    score += max(0, round(8 - disagreement * 40))
    if disagreement > .12:
        missing.append("승패 모형과 득점 모형의 예측 차이")
    score = max(35, min(94, score))  # Injuries remain unavailable from a single authoritative league feed.
    label = "HIGH" if score >= 80 else ("MEDIUM" if score >= 65 else "LOW")
    return score, label, missing


def _reasons(home: Any, away: Any, home_pitcher: Any | None, away_pitcher: Any | None, f: dict[str, Any]) -> list[str]:
    reasons: list[str] = []
    if abs(f["starter_era_diff"]) >= .35:
        winner = home.team.name if f["starter_era_diff"] > 0 else away.team.name
        reasons.append(f"{winner} 선발이 시즌 ERA 비교에서 우세합니다.")
    if abs(f["recent_10_win_rate_diff"]) >= .15:
        winner = home.team.name if f["recent_10_win_rate_diff"] > 0 else away.team.name
        reasons.append(f"{winner}의 최근 10경기 승률이 더 높습니다.")
    if abs(f["ops_diff"]) >= .025:
        winner = home.team.name if f["ops_diff"] > 0 else away.team.name
        reasons.append(f"{winner}가 시즌 OPS에서 우세합니다.")
    if abs(f["runs_allowed_per_game_diff"]) >= .35:
        winner = home.team.name if f["runs_allowed_per_game_diff"] > 0 else away.team.name
        reasons.append(f"{winner}의 경기당 실점 억제력이 더 좋습니다.")
    if abs(f["bullpen_proxy_diff"]) >= .45:
        winner = home.team.name if f["bullpen_proxy_diff"] > 0 else away.team.name
        reasons.append(f"{winner}가 팀 ERA와 선발 소화 이닝 기반 불펜 부담 추정에서 우세합니다.")
    if abs(f["starter_fip_diff"]) >= .5:
        winner = home.team.name if f["starter_fip_diff"] > 0 else away.team.name
        reasons.append(f"{winner} 선발이 수비 영향 축소 지표(FIP 추정)에서 우세합니다.")
    if (f["home_starter_opponent_weight"] >= .12 or f["away_starter_opponent_weight"] >= .12) and abs(f["starter_opponent_era_diff"]) >= .45:
        winner = home.team.name if f["starter_opponent_era_diff"] > 0 else away.team.name
        reasons.append(f"{winner} 선발의 현재 상대팀 상대 기록이 표본 축소 후에도 우세합니다.")
    if f["head_to_head_games"] >= 3 and abs(f["head_to_head_run_diff"]) >= .35:
        winner = home.team.name if f["head_to_head_run_diff"] > 0 else away.team.name
        reasons.append(f"{winner}가 최근 팀 간 맞대결 득실점에서 우세합니다(소표본 보정).")
    if f["home_lineup_confirmed"] and f["away_lineup_confirmed"] and abs(f["lineup_strength_diff"]) >= .08:
        winner = home.team.name if f["lineup_strength_diff"] > 0 else away.team.name
        reasons.append(f"확정 라인업의 시즌 생산력은 {winner}가 우세합니다.")
    if min(int(f["home_lineup_bvp_coverage"]), int(f["away_lineup_bvp_coverage"])) >= 3 and abs(f["lineup_bvp_diff"]) >= .035:
        winner = home.team.name if f["lineup_bvp_diff"] > 0 else away.team.name
        reasons.append(f"{winner} 확정 타선의 상대 선발 맞대결 기록이 표본 축소 후 우세합니다.")
    if not reasons:
        reasons.append("주요 지표 차이가 작아 접전 가능성이 높게 평가됩니다.")
    reasons.append("홈 어드밴티지는 모든 경기에서 보수적으로 반영됩니다.")
    return reasons[:4]
